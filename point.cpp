#include "point.h"

#include <cmath>      /* std::sqrt */
#include <iomanip>    /* std::setw, std::fixed, std::setprecision */

/* Автор: Горчак Дмитрий, 212
   Конструктор по умолчанию: точка в начале координат.
   Параметров нет.
   Ничего не возвращает. */
Point::Point() : x_(0.0f), y_(0.0f) {
}

/* Автор: Горчак Дмитрий, 212
   Конструктор точки с заданными координатами.
   Параметры:
      x - абсцисса
      y - ордината
   Ничего не возвращает. */
Point::Point(float x, float y) : x_(x), y_(y) {
}

/* Автор: Горчак Дмитрий, 212
   Читает координату x.
   Параметров нет.
   Возвращает значение закрытого поля x_. */
float Point::get_x() const {
    return x_;
}

/* Автор: Горчак Дмитрий, 212
   Читает координату y.
   Параметров нет.
   Возвращает значение закрытого поля y_. */
float Point::get_y() const {
    return y_;
}

/* Автор: Горчак Дмитрий, 212
   Записывает координату x.
   Параметры:
      x - новое значение абсциссы
   Ничего не возвращает. */
void Point::set_x(float x) {
    x_ = x;
}

/* Автор: Горчак Дмитрий, 212
   Записывает координату y.
   Параметры:
      y - новое значение ординаты
   Ничего не возвращает. */
void Point::set_y(float y) {
    y_ = y;
}

/* Автор: Горчак Дмитрий, 212
   Расстояние между двумя точками по теореме Пифагора.
   Параметры:
      other - вторая точка
   Возвращает расстояние (всегда неотрицательное). */
float Point::distance_to(const Point &other) const {
    float dx = x_ - other.x_;
    float dy = y_ - other.y_;

    return std::sqrt(dx * dx + dy * dy);
}

/* Автор: Горчак Дмитрий, 212
   Печатает координаты точки в поток.
   Метод виртуальный: у наследников строка вывода своя.
   Параметры:
      out - поток вывода (экран или файл)
   Ничего не возвращает. */
void Point::print(std::ostream &out) const {
    out << std::fixed << std::setprecision(2);
    out << "Point(x = " << std::setw(7) << x_
        << ", y = " << std::setw(7) << y_ << ")";
}

/* Автор: Горчак Дмитрий, 212
   Название фигуры для таблицы.
   Параметров нет.
   Возвращает строку "Point". */
const char *Point::type_name() const {
    return "Point";
}
