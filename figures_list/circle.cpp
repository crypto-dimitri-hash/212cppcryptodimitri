#include "circle.h"

#include <iomanip>      /* std::setw, std::fixed, std::setprecision */
#include <stdexcept>    /* std::invalid_argument */

/* Число pi. Константа объявлена static: она нужна только в этом файле
   (внутреннее связывание, занятие 5). */
static const double PI = 3.14159265358979323846;

/* Автор: Горчак Дмитрий, 212
   Конструктор по умолчанию: круг нулевого радиуса в начале координат.
   Параметров нет.
   Ничего не возвращает. */
Circle::Circle() : Point(), r_(0.0f) {
}

/* Автор: Горчак Дмитрий, 212
   Конструктор круга. Центр передаётся конструктору базового класса Point,
   радиус проверяется тем же методом set_r, что и при изменении извне.
   Параметры:
      x - абсцисса центра
      y - ордината центра
      r - радиус (r >= 0)
   Ничего не возвращает; при r < 0 бросает std::invalid_argument. */
Circle::Circle(float x, float y, float r) : Point(x, y), r_(0.0f) {
    set_r(r);
}

/* Автор: Горчак Дмитрий, 212
   Читает радиус.
   Параметров нет.
   Возвращает значение закрытого поля r_. */
float Circle::get_r() const {
    return r_;
}

/* Автор: Горчак Дмитрий, 212
   Записывает радиус. Проверка выполняется здесь -- это единственный путь
   к закрытому полю, поэтому круг с отрицательным радиусом создать нельзя.
   Параметры:
      r - новый радиус (r >= 0)
   Ничего не возвращает; при r < 0 бросает std::invalid_argument. */
void Circle::set_r(float r) {
    if (r < 0.0f) {
        throw std::invalid_argument("radius must be >= 0");
    }
    r_ = r;
}

/* Автор: Горчак Дмитрий, 212
   Вычислимый атрибут: площадь круга S = pi * r * r.
   Значение не хранится в объекте, а считается при каждом вызове,
   поэтому оно всегда согласовано с текущим радиусом.
   Параметров нет.
   Возвращает площадь круга. */
double Circle::area() const {
    double r = static_cast<double>(r_);

    return PI * r * r;
}

/* Автор: Горчак Дмитрий, 212
   Печатает параметры круга и его площадь.
   Параметры:
      out - поток вывода
   Ничего не возвращает. */
void Circle::print(std::ostream &out) const {
    out << std::fixed << std::setprecision(2);
    out << "Circle(x = " << std::setw(7) << get_x()
        << ", y = " << std::setw(7) << get_y()
        << ", r = " << std::setw(6) << r_
        << ", area = " << std::setw(9) << area() << ")";
}

/* Автор: Горчак Дмитрий, 212
   Название фигуры для таблицы.
   Параметров нет.
   Возвращает строку "Circle". */
const char *Circle::type_name() const {
    return "Circle";
}
