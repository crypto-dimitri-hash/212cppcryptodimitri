/* cone.h -- класс Cone: конус, стоящий на плоскости (x, y, r, h).
   Третий уровень иерархии: Cone -- это Circle плюс высота,
   то есть любой конус описывается четырьмя числами.
   Объём -- вычислимый атрибут: метод, а не хранимое поле.

   О названии. В задании фигура названа пирамидой, но у неё круглое
   основание и высота, и преподаватель уточнил, что речь идёт о конусе.
   Поэтому класс назван Cone -- так же, как фигура называется в задаче.
   Автор: Горчак Дмитрий, 212 */

#ifndef CONE_H
#define CONE_H

#include <ostream>

#include "circle.h"

/* Конус с основанием-кругом радиуса r и высотой h.
   Объём считается по общему правилу V = S * h / 3, где S -- площадь
   основания, взятая у базового класса Circle; для круга это pi * r * r,
   то есть V = pi * r * r * h / 3.
   Для сравнения оставлен метод volume_ngon(n): объём пирамиды с
   правильным n-угольником в основании, вписанным в тот же круг. */
class Cone : public Circle {
public:
    Cone();                                         /* вырожденный конус: r = 0, h = 0 */
    Cone(float x, float y, float r, float h);

    float get_h() const;
    void set_h(float h);                            /* h >= 0, иначе std::invalid_argument */

    /* Вычислимый атрибут: объём V = S(основания) * h / 3 */
    double volume() const;

    /* Объём пирамиды с правильным n-угольником в основании, вписанным
       в круг радиуса r (n >= 3). При росте n стремится к volume(). */
    double volume_ngon(int n) const;

    /* Высота поверхности конуса над точкой (px, py): h в центре,
       0 на границе основания и вне него. Нужна для ландшафта в gnuplot. */
    double height_at(float px, float py) const;

    void print(std::ostream &out) const override;
    const char *type_name() const override;

private:
    float h_;                                       /* высота */
};

#endif
